/*
 * 「解説」タブの本文
 *   R(単語, 読み, 意味) … タップで読み上げられるロシア語の例。アクセントは data.js と同じく + で書きます。
 *   T(見出しの配列, 行の配列) … 表
 */
function R(w, kana, ja) {
  return '<span class="ex" data-say="' + plain(w) + '" role="button" tabindex="0">' +
    '<span class="ru">' + accent(w) + '</span>' +
    (kana ? '<span class="ex-kana">' + kana + '</span>' : '') +
    (ja ? '<span class="ex-ja">' + ja + '</span>' : '') + '</span>';
}
function T(head, rows) {
  return '<div class="table-wrap"><table><thead><tr>' + head.map((h) => '<th>' + h + '</th>').join('') +
    '</tr></thead><tbody>' + rows.map((r) => '<tr>' + r.map((c) => '<td>' + c + '</td>').join('') + '</tr>').join('') +
    '</tbody></table></div>';
}
// 表の中で使う短い形（読み上げ付き・訳なし）
function S(w) { return '<span class="ex ex-s" data-say="' + plain(w) + '" role="button" tabindex="0"><span class="ru">' + accent(w) + '</span></span>'; }

